// Runs in Expo config (Node), never in the app. Conservative installed runtime dependency closure, not devDeps.
const { existsSync, readFileSync, readdirSync, realpathSync, statSync, writeFileSync } = require("node:fs");
const { createRequire } = require("node:module");
const { dirname, join, resolve, sep } = require("node:path");

const appRoot = resolve(__dirname, "../../..");
const repoRoot = resolve(appRoot, "../..");
const visited = new Set();
const notices = [];

function visit(directory) {
	const root = realpathSync(directory);
	if (visited.has(root)) return;
	visited.add(root);
	const manifestPath = join(root, "package.json");
	const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
	const localRequire = createRequire(manifestPath);
	const files = readdirSync(root)
		.filter((name) => /^(licen[cs]e|copying|notice)([.-]|$)/i.test(name))
		.sort();
	const texts = files
		.filter((name) => !name.endsWith(".json"))
		.map((name) => {
			const file = join(root, name);
			if (!statSync(file).isFile()) return "";
			return `${name}\n${readFileSync(file, "utf8").replace(/\r\n/g, "\n").trim()}`;
		});
	if (root !== appRoot) {
		notices.push({
			title: `${manifest.name} ${manifest.version}`,
			text: [
				typeof manifest.license === "string" ? manifest.license : "Licence not declared in package metadata.",
				...texts,
			].join("\n\n"),
		});
	}
	// Workspace peers are type-only (notably the server API); third-party peers may ship native/runtime code.
	const peers = root.includes(`${sep}node_modules${sep}`) ? manifest.peerDependencies : {};
	const dependencies = { ...peers, ...manifest.optionalDependencies, ...manifest.dependencies };
	for (const name of Object.keys(dependencies).sort()) {
		const candidate = localRequire.resolve
			.paths(name)
			?.map((path) => join(path, name, "package.json"))
			.find(existsSync);
		if (candidate) visit(dirname(candidate));
		else if (name in (manifest.dependencies ?? {}) && !(name in (manifest.optionalDependencies ?? {}))) {
			throw new Error(`Install dependencies before generating licences: missing ${name} from ${manifest.name}`);
		}
	}
}

visit(appRoot);
notices.sort((a, b) => (a.title < b.title ? -1 : a.title > b.title ? 1 : 0));
const native = readFileSync(join(repoRoot, "packages/forme-native/THIRD_PARTY_NOTICES.md"), "utf8");
const nativeNotices = native.split(/^## /m).map((section, index) => {
	const newline = section.indexOf("\n");
	return { title: index === 0 ? "Forme native" : section.slice(0, newline), text: section.slice(newline + 1).trim() };
});
const fontRoot = join(appRoot, "assets/fonts");
const fontNotices = readdirSync(fontRoot)
	.filter((name) => /OFL|LICEN[CS]E/i.test(name))
	.sort()
	.map((name) => ({ title: name, text: readFileSync(join(fontRoot, name), "utf8").trim() }));
const output = `// Generated by generate.cjs during Expo config. Legal notices retain upstream wording.\n// prettier-ignore\nexport const nativeNotices = ${JSON.stringify([...nativeNotices, ...fontNotices])};\n// prettier-ignore\nexport const javascriptNotices = ${JSON.stringify(notices)};\n`;
const target = join(__dirname, "notices.ts");
if (!existsSync(target) || readFileSync(target, "utf8") !== output) writeFileSync(target, output);
