export type IconName = keyof typeof icons;

// Icons that point somewhere are mirrored in right-to-left layouts.
const DIRECTIONAL_ICONS = new Set<IconName>([
	"arrow-left",
	"arrow-right",
	"arrow-u-up-left",
	"arrow-u-up-right",
	"caret-left",
	"caret-right",
]);

export type IconProps = {
	name: IconName;
	/** The filled glyph. The design system reserves it for the selected navigation item. */
	filled?: boolean | undefined;
	/** Glyph size in pt: 16 inline meta, 20 list rows, 22 toolbars, 24 tab bar and nav bar (tokens `size.icon`). */
	size?: number | undefined;
	/** Defaults to the theme `ink`. */
	color?: string | undefined;
};

/** A decorative Phosphor glyph: the control it sits in carries the accessible name. */
export function Icon({ name, filled = false, size = 20, color }: IconProps) {
	const { colors } = useTheme();
	const Glyph = icons[name];

	return (
		<Glyph
			size={size}
			color={color ?? colors.ink}
			weight={filled ? "fill" : "regular"}
			mirrored={I18nManager.isRTL && DIRECTIONAL_ICONS.has(name)}
		/>
	);
}
