import { execFileSync } from "node:child_process";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { packageRoot, sha256 } from "./artifact.mjs";

const metadata = JSON.parse(
	execFileSync("cargo", ["metadata", "--locked", "--format-version", "1"], {
		cwd: join(packageRoot, "rust"),
		encoding: "utf8",
		maxBuffer: 16 * 1024 * 1024,
	}),
);
const resolved = new Set(metadata.resolve.nodes.map((node) => node.id));
const crates = metadata.packages
	.filter((crate) => resolved.has(crate.id) && crate.id !== metadata.resolve.root)
	.sort((a, b) => `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`, "en"));
const parts = [
	"# Third-party notices: Forme Native",
	"Generated by `node packages/forme-native/scripts/notices.mjs` from `cargo metadata --locked`. Do not edit by hand.",
	`Cargo.lock SHA-256: \`${sha256(await readFile(join(packageRoot, "rust/Cargo.lock")))}\`.`,
	`Includes all ${crates.length} resolved third-party Rust crates, including build dependencies and target-specific dependencies. Licence expressions below are upstream declarations; OR alternatives remain alternatives.`,
];

async function appendFile(directory, path) {
	parts.push(
		`### ${path}`,
		`\`\`\`text\n${(await readFile(join(directory, path), "utf8"))
			.replace(/\r\n/g, "\n")
			.replace(/[ \t]+$/gm, "")
			.trimEnd()}\n\`\`\``,
	);
}

for (const crate of crates) {
	if (!crate.license && !crate.license_file) throw new Error(`No licence declaration: ${crate.name}@${crate.version}`);
	parts.push(`## ${crate.name} ${crate.version}`, `Licence: ${crate.license ?? "see bundled licence file"}.`);
	if (crate.repository) parts.push(`Source: ${crate.repository}`);
	const directory = dirname(crate.manifest_path);
	const files = new Set();
	async function collect(base = "") {
		for (const entry of await readdir(join(directory, base), { withFileTypes: true })) {
			if (!base && !/^(licen[cs]e|copying|notice|copyright)([._-]|$)/i.test(entry.name)) continue;
			const path = base ? `${base}/${entry.name}` : entry.name;
			if (entry.isDirectory()) await collect(path);
			else if (entry.isFile()) files.add(path);
		}
	}
	await collect();
	if (crate.license_file) files.add(crate.license_file);
	if (files.size === 0) {
		// cms 0.2.3 omits licence files from its crate; preserve its published licence statement.
		const readme = await readFile(join(directory, "README.md"), "utf8");
		const section = readme.match(/^## Licen[cs]e\s*\n([\s\S]*?)(?=^#{1,3} |$(?![\s\S]))/m);
		if (!section) throw new Error(`No bundled licence text or README licence section: ${crate.name}`);
		parts.push(
			"The published crate contains no separate licence files. Upstream README declaration:",
			`\`\`\`text\n${section[1].trim()}\n\`\`\``,
		);
	}
	for (const file of [...files].sort()) await appendFile(directory, file);
	if (crate.name === "harfbuzz-sys") {
		const versionHeader = await readFile(join(directory, "harfbuzz/src/hb-version.h"), "utf8");
		const version = versionHeader.match(/#define HB_VERSION_STRING "([^"]+)"/)?.[1];
		if (!version) throw new Error("Cannot determine bundled HarfBuzz version");
		parts.push(
			`## HarfBuzz ${version} (bundled by harfbuzz-sys)`,
			"Licence: Old-MIT. Includes the bundled Microsoft USE notice.",
		);
		await appendFile(directory, "harfbuzz/COPYING");
		await appendFile(directory, "harfbuzz/src/ms-use/COPYING");
	}
}

await writeFile(join(packageRoot, "THIRD_PARTY_NOTICES.md"), `${parts.join("\n\n")}\n`);
console.log(`Generated notices for ${crates.length} Rust crates and bundled HarfBuzz.`);
